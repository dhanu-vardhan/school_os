package com.schoolos.analytics;

import com.schoolos.analytics.AnalyticsContract.Envelope;
import com.schoolos.analytics.AnalyticsContract.MetricDefinition;
import com.schoolos.common.Uuids;
import com.schoolos.security.CurrentUser;
import com.schoolos.security.PolicyService;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.core.task.TaskExecutor;
import org.springframework.http.HttpStatus;
import org.springframework.security.task.DelegatingSecurityContextTaskExecutor;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.time.Instant;
import java.util.List;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import java.util.stream.Collectors;

/**
 * Async, step-up-gated export jobs. The tenant scope is resolved by the already-validated
 * JWT and propagated into the worker thread; no request field can widen it. Results are
 * watermarked and keyed by a fresh per-export id, with optional idempotency for retries.
 */
@Service
public class AnalyticsExportService {

    public enum JobStatus { PENDING, RUNNING, COMPLETED, FAILED }

    public record ExportJob(
            UUID id,
            JobStatus status,
            String format,
            List<String> metricIds,
            String watermark,
            Instant createdAt,
            Instant completedAt,
            String error,
            String content) {}

    private final AnalyticsService delegate;
    private final PolicyService policy;
    private final CurrentUser currentUser;
    private final TaskExecutor executor;
    private final ConcurrentHashMap<UUID, ExportJob> jobs = new ConcurrentHashMap<>();
    private final ConcurrentHashMap<String, UUID> idempotencyKeys = new ConcurrentHashMap<>();

    public AnalyticsExportService(
            AnalyticsService delegate,
            PolicyService policy,
            CurrentUser currentUser,
            @Qualifier("analyticsExportExecutor") TaskExecutor executor) {
        this.delegate = delegate;
        this.policy = policy;
        this.currentUser = currentUser;
        this.executor = new DelegatingSecurityContextTaskExecutor(executor);
    }

    /** Start a job. Step-up is enforced here, before any work is queued. */
    public ExportJob start(AsyncExportRequest request, AnalyticsFilters filters) {
        policy.require(currentUser, PolicyService.ANALYTICS_EXPORT);
        if (!Boolean.TRUE.equals(request.confirmWatermark())) {
            throw bad("Watermark confirmation is required before an export is generated");
        }
        Set<String> known = delegate.dictionary().stream()
                .map(MetricDefinition::id).collect(Collectors.toSet());
        for (String metricId : request.metricIdsOrEmpty()) {
            if (!known.contains(metricId)) throw bad("unknown metricId: " + metricId);
        }

        String key = idempotencyKey(request, filters);
        if (key != null) {
            UUID existing = idempotencyKeys.get(key);
            if (existing != null) return jobs.get(existing);
        }

        UUID id = Uuids.newV7();
        String watermark = "Confidential · generated by SchoolOS · " + Instant.now();
        ExportJob pending = new ExportJob(id, JobStatus.PENDING, request.format(),
                List.copyOf(request.metricIdsOrEmpty()), watermark, Instant.now(), null, null, null);
        jobs.put(id, pending);
        if (key != null) idempotencyKeys.putIfAbsent(key, id);
        executor.execute(() -> run(id, request, filters, watermark));
        return pending;
    }

    public ExportJob status(UUID id) {
        ExportJob job = jobs.get(id);
        if (job == null) throw new ResponseStatusException(HttpStatus.NOT_FOUND, "unknown export job");
        return job;
    }

    private void run(UUID id, AsyncExportRequest request, AnalyticsFilters filters, String watermark) {
        ExportJob running = jobs.get(id);
        jobs.put(id, new ExportJob(id, JobStatus.RUNNING, running.format(), running.metricIds(),
                watermark, running.createdAt(), null, null, null));
        try {
            Envelope<String> result = delegate.export(
                    new ExportRequest(request.format(), request.metricIdsOrEmpty()), filters);
            jobs.put(id, new ExportJob(id, JobStatus.COMPLETED, running.format(), running.metricIds(),
                    watermark, running.createdAt(), Instant.now(), null, result.data()));
        } catch (RuntimeException e) {
            // Never echo upstream messages: they can contain metric values or personal data.
            jobs.put(id, new ExportJob(id, JobStatus.FAILED, running.format(), running.metricIds(),
                    watermark, running.createdAt(), Instant.now(), "Export failed", null));
        }
    }

    private String idempotencyKey(AsyncExportRequest request, AnalyticsFilters filters) {
        String key = request.idempotencyKey();
        if (key == null || key.isBlank()) return null;
        return currentUser.schoolId() + "|" + currentUser.subject() + "|" + key.trim() + "|" + filters;
    }

    private static ResponseStatusException bad(String message) {
        return new ResponseStatusException(HttpStatus.BAD_REQUEST, message);
    }
}
